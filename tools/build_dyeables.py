"""Build plugin/data/dyeables.tsv: every item the game marks dyeable (ItemInfo._isDyeable).

Reads the game's own tables (extract them first with paz.py):
    extracted/0008/gamedata/binarystaticinfo__/bin/iteminfo.staticinfo{header,body}
    extracted/0020/gamedata/stringtable/binary__/eng/item.paloc
Only the leading fields of each ItemInfo record are read; their order follows the field
order documented by Master Looter's cdtables.py (MIT).
"""
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIN = os.path.join(ROOT, "extracted", "0008", "gamedata", "binarystaticinfo__", "bin")
PALOC = os.path.join(ROOT, "extracted", "0020", "gamedata", "stringtable", "binary__", "eng", "item.paloc")
OUT = os.path.join(ROOT, "plugin", "data", "dyeables.tsv")

FLAGS = ("is_reward_loot_drop", "lost_item_recovery_type", "is_editable_grime", "is_dyeable",
         "discardable", "use_average_price", "is_housing_only", "is_destroy_when_broken",
         "discard_attach_terrain", "is_blocked_store_sell", "enable_equip_in_clone_actor",
         "is_logout_at_use_item", "is_preserved_on_extract", "is_has_item_use_data_inventory_buff",
         "is_preorder_item", "is_tower_shield_item", "is_shield_item",
         "hide_from_inventory_on_pop_item", "is_save_game_data_at_use_item",
         "enable_alert_system_to_ui", "is_wild", "is_editor_usable", "use_map_icon_alert",
         "is_extract_able_item", "use_immediately", "apply_max_stack_cap",
         "is_all_gimmick_sealable", "is_register_trade_market", "can_disassemble",
         "delete_by_gimmick_unlock", "use_drop_set_target", "item_type", "knowledge_obtain_type",
         "item_tier", "usable_alert_type", "item_charge_type", "apply_drop_stat_type")


def load_table(name):
    h = open(os.path.join(BIN, name + ".staticinfoheader"), "rb").read()
    b = open(os.path.join(BIN, name + ".staticinfobody"), "rb").read()
    cnt = int.from_bytes(h[:2], "little")
    ks = (len(h) - 2) // cnt - 4
    ents, p = [], 2
    for _ in range(cnt):
        ents.append((int.from_bytes(h[p:p + ks], "little"), struct.unpack_from("<I", h, p + ks)[0]))
        p += ks + 4
    offs = sorted(o for _, o in ents) + [len(b)]
    nxt = {o: offs[i + 1] for i, o in enumerate(offs[:-1])}
    return [(k, b[o:nxt[o]]) for k, o in ents]


def load_paloc(path):
    d = open(path, "rb").read()
    if d[:5] == b"paloc":   # 2.05: "paloc" header, u32 packed, u32 size, LZ4 block from 0x200
        import lz4.block
        d = lz4.block.decompress(d[0x200:], uncompressed_size=struct.unpack_from("<I", d, 13)[0])
    cnt = struct.unpack_from("<I", d, len(d) - 4)[0]
    off, out = 0, {}
    for _ in range(cnt):
        off += 8
        kl, = struct.unpack_from("<I", d, off); off += 4
        key = d[off:off + kl].decode("utf-8", "replace"); off += kl
        vl, = struct.unpack_from("<I", d, off); off += 4
        out[int(key)] = d[off:off + vl].decode("utf-8", "replace"); off += vl
    return out


def head(rec):
    p = 0
    sl = struct.unpack_from("<I", rec, p)[0]
    skey = rec[4:4 + sl].decode("utf-8", "replace"); p = 4 + sl
    key = struct.unpack_from("<I", rec, p)[0]; p += 4
    p += 1 + 2 + 8                      # is_blocked, max_endurance, max_stack_count
    flags = dict(zip(FLAGS, rec[p:p + len(FLAGS)])); p += len(FLAGS)
    p += 4 * 6                          # six u32 references
    equip_type = struct.unpack_from("<I", rec, p)[0]
    return skey, key, flags, equip_type


def main():
    names = load_paloc(PALOC)
    rows, total = [], 0
    for row, (k, rec) in enumerate(load_table("iteminfo")):
        total += 1
        skey, key, flags, equip = head(rec)
        assert key == k, (k, key, skey)
        if flags["is_dyeable"]:
            nm = names.get((key << 32) | 0x70, "")
            rows.append((row, key, skey, equip, nm))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# row\tkey\tstring_key\tequip_type\tname   (generated by tools/build_dyeables.py)\n")
        for r in rows:
            f.write("%d\t%d\t%s\t%d\t%s\n" % r)
    print("items", total, "dyeable", len(rows))
    for r in rows[:: max(1, len(rows) // 15)]:
        print("  ", r)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    main()
